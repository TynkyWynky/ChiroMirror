import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const appMigrationFiles = [
  "20260922000000_legacy_profile_groups.sql",
  "20260922000100_neutral_site_role.sql",
  "20260922000200_app_members_rbac.sql",
  "20260923000100_app_agenda.sql",
  "20260923000200_app_tasks.sql",
  "20260923000300_app_finance.sql",
  "20260923000400_app_notifications.sql"
];

export function buildAppInstallSql() {
  const migrations = appMigrationFiles.map(name => ({
    name, source: readFileSync(new URL(`../supabase/migrations/${name}`, import.meta.url), "utf8").replaceAll("\r\n", "\n")
  }));
  const tables = migrations.flatMap(({ source }) => [...source.matchAll(/^create table public\.(\w+)/gm)].map(match => match[1]));
  const appMigrations = migrations.filter(({ name }) => name >= "20260922000200");
  const functions = appMigrations.flatMap(({ source }) => [...source.matchAll(/^create function public\.(\w+)/gm)].map(match => match[1]));
  const names = values => values.map(value => `'${value}'`).join(", ");
  const sections = migrations.map(({ name, source }) => {
    // Preserve migration SQL verbatim except its outer transaction statements.
    // One transaction is required so failure in a later phase rolls back all phases.
    if ((source.match(/^begin;\s*$/gm) ?? []).length !== 1 || (source.match(/^commit;\s*$/gm) ?? []).length !== 1) {
      throw new Error(`Unexpected transaction wrappers: ${name}`);
    }
    const body = source.replace(/^begin;[ \t]*\n/m, "").replace(/^commit;[ \t]*\n?$/m, "").trimEnd();
    const hash = createHash("sha256").update(source).digest("hex");
    return `-- BEGIN MIGRATION ${name}\n-- Source SHA-256 (LF): ${hash}\n${body}\n-- END MIGRATION ${name}`;
  });

  return `-- GENERATED by node scripts/prepare-app-install.mjs; do not hand-edit.
-- Install bundle: 20260922000000 through 20260923000400.
-- Includes the legacy profile-column prerequisite and six APP migrations.
-- Existing SITE database ONLY, with no APP tables or prior APP migrations.
-- Prerequisites: inspect the target project's schema/history and take a backup;
-- execute as its database administrator in Supabase SQL Editor or psql.
-- This file never creates Auth accounts, grants APP roles, sends email or runs seed.
-- Existing SITE profiles/content remain intact; new Auth profiles become neutral.
-- Any pre-existing APP object (including a completed install) causes a safe refusal.
-- If installation is partial, inspect it and apply ONLY the missing versioned migrations.
-- Do not mark migration history as applied without reconciling this manual install.
-- After success: run verify-app.sql, then customize bootstrap-app-admin.sql once.
-- Grant no role to all SITE admins: choose and verify one existing Auth email.
-- Finally log in at /leiding-login/?app=home (or the configured ADMIN_PATH_SLUG),
-- create/link the administrator's member entry and assign other roles in the APP UI.
-- Notifications require the separately configured scheduled worker/VAPID keys for Push.

begin;
set local lock_timeout = '10s';
set local statement_timeout = '120s';

do $preflight$
declare prior_app_history boolean;
begin
  if current_setting('server_version_num')::integer < 140000 then
    raise exception 'APP installation requires PostgreSQL 14 or newer';
  end if;
  if not pg_try_advisory_xact_lock(20260924, 1) then
    raise exception 'Another APP installation is running';
  end if;
  if to_regclass('public.profiles') is null or to_regclass('auth.users') is null then
    raise exception 'Existing SITE/Auth schema is required; do not use this bundle on an empty database';
  end if;
  if not exists (select 1 from pg_roles where rolname = 'anon')
    or not exists (select 1 from pg_roles where rolname = 'authenticated')
    or not exists (select 1 from pg_roles where rolname = 'service_role' and rolbypassrls) then
    raise exception 'Expected Supabase anon/authenticated/service_role database roles are missing';
  end if;
  -- can_manage_group(text) is created by the neutral-role migration below. Older SITE
  -- installations need not have it yet; it is not an installation prerequisite.
  if to_regprocedure('auth.uid()') is null
    or to_regprocedure('public.is_site_admin()') is null
    or to_regprocedure('public.is_site_editor()') is null
    or to_regprocedure('public.handle_new_profile()') is null then
    raise exception 'Expected SITE authorization functions are missing; inspect the schema first';
  end if;
  if not exists (select 1 from pg_trigger where tgrelid = 'auth.users'::regclass
    and tgname = 'on_auth_user_created' and not tgisinternal
    and tgfoid = 'public.handle_new_profile()'::regprocedure and tgenabled in ('O', 'A')) then
    raise exception 'Expected active Auth profile trigger is missing; inspect the schema first';
  end if;
  if exists (select 1 from unnest(array[${names(tables)}]) name
    where to_regclass('public.' || name) is not null)
    or exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'public' and p.proname = any(array[${names(functions)}])) then
    raise exception 'APP objects already exist. No changes made: verify an existing install or apply only missing migrations';
  end if;
  if to_regclass('supabase_migrations.schema_migrations') is not null then
    execute 'select exists (select 1 from supabase_migrations.schema_migrations where version::text = any($1))'
      into prior_app_history using array[${names(appMigrations.map(({ name }) => name.slice(0, 14)))}];
    if prior_app_history then
      raise exception 'APP migration history exists but APP objects are absent; reconcile the history before continuing';
    end if;
  end if;
end;
$preflight$;

${sections.join("\n\n")}

-- Delivered only when the complete transaction commits; refresh the REST schema cache.
notify pgrst, 'reload schema';
commit;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("../supabase/install-app.sql", import.meta.url), buildAppInstallSql(), "utf8");
  console.log("Prepared supabase/install-app.sql from one legacy prerequisite and six APP migrations. No database connection or execution.");
}
